const fs = require('node:fs');
const ts = require('typescript');
const assert = require('node:assert/strict');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, filename);
const { MODULES, emptyPlan, saveDraft, setReviewed, parsePlan, planHtml } = require('../src/data/plan.ts');
let plan = emptyPlan();
assert.equal(MODULES.length, 8);
assert.throws(() => setReviewed(plan, 'overview', true));
assert.throws(() => setReviewed(plan, 'summary', true));
for (const m of MODULES) { plan = saveDraft(plan, m.id, `Draft for ${m.title}`); plan = setReviewed(plan, m.id, true); }
assert.equal(plan.sections.summary.reviewed, true);
const previous = plan;
plan = saveDraft(plan, 'products', 'A revised offer');
assert.equal(plan.sections.summary.reviewed, false);
assert.equal(plan.sections.products.reviewed, false);
assert.equal(previous.sections.products.reviewed, true);
assert.equal(plan.sections.market.reviewed, true);
for (let n = 0; n < 15; n++) plan = saveDraft(plan, 'overview', `Version ${n}`);
assert.equal(plan.sections.overview.versions.length, 10);
assert.equal(plan.sections.overview.versions[0].text, 'Version 5');
plan = saveDraft(plan, 'overview', 'Version 5', true);
assert.equal(plan.sections.overview.text, 'Version 5');
assert.deepEqual(parsePlan(JSON.stringify(plan)), plan);
assert.throws(() => parsePlan('{"schema":2}'));
assert.throws(() => saveDraft(plan, 'overview', 'a'.repeat(12001)));
assert.ok(planHtml('<script>alert(1)</script>', plan).includes('&lt;script&gt;'));
assert.ok(!planHtml('<script>alert(1)</script>', plan).includes('<script>'));
assert.ok(planHtml('Business', emptyPlan()).includes('Not started'));
console.log('Plan checks passed: review dependencies, immutable updates, history bounds, restore, validation and safe PDF markup.');
